# 프로파일 목록 요약 출력 함수
list_profiles <- function() {
  purrr::map_df(INDUSTRY_PROFILES, ~ {
    data.frame(
      프로파일_키 = .x$name_en,
      한국어명    = .x$name_ko,
      소득_가중치 = .x$w_income,
      인구_가중치 = .x$w_pop,
      교육_가중치 = .x$w_edu,
      청년층_가중치 = .x$w_young,
      영유아_가중치 = .x$w_under5
    )
  }, .id = "profile_key")
}
